CREATE TABLE IF NOT EXISTS funds (id INTEGER PRIMARY KEY, doc TEXT NOT NULL, detail TEXT NOT NULL, nav TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS screens (
  id TEXT PRIMARY KEY, client_id TEXT NOT NULL, name TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
  config TEXT NOT NULL, created TEXT NOT NULL, updated TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS watchlist (client_id TEXT NOT NULL, fund_id INTEGER NOT NULL, PRIMARY KEY (client_id, fund_id));
